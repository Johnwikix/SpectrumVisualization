// Regenerate Folia's native 2D scene planners and Hanabi profiles (AGPL-3.0).
// Usage: node Build/FoliaNative/sync.mjs <folia-major checkout>
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { stripTypeScriptTypes } from 'node:module';
import { fileURLToPath } from 'node:url';

if (!process.argv[2]) throw new Error('Pass the upstream folia-major checkout explicitly.');
const upstream = path.resolve(process.argv[2]);
const revision = '6ee9404f7957b8ea841a46bad8b085a5a604a3cf';
const actual = execFileSync('git', ['--git-dir=' + path.join(upstream, '.git'), 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
if (actual !== revision) throw new Error('Expected the pinned folia-major commit ' + revision + ', found ' + actual);
const root = path.join(upstream, 'src/components/visualizer');
const output = fileURLToPath(new URL('../../Effects/Folia/', import.meta.url));
function readTypeScript(file) {
    let source = fs.readFileSync(path.join(root, file), 'utf8');
    // Node's strip-only parser needs an explicit assignment for the Pen parameter properties.
    if (file.endsWith('metaphorFigures.ts')) {
        const first = source.indexOf('    constructor(');
        const last = source.indexOf('        this.cos', first);
        const properties = [...source.slice(first, last).matchAll(/private readonly (\w+)\s*[:=]/g)].map(match => match[1]);
        source = source.slice(0, first) + properties.map(key => '    readonly ' + key + ';\n').join('') +
            source.slice(first, last).replaceAll('private readonly ', '') +
            properties.map(key => '        this.' + key + ' = ' + key + ';\n').join('') + source.slice(last);
    }
    return stripTypeScriptTypes(source);
}

function f(value) {
    if (!Number.isFinite(value)) throw new Error('Non-finite coordinate in Folia native data.');
    return Number(value.toPrecision(7)) + 'f';
}
const str = value => JSON.stringify(value);
const header = '// Generated by Build/FoliaNative/sync.mjs from folia-major 6ee9404f (AGPL-3.0).\n\nnamespace WinExSpectrumTest.Effects.Folia;\n';
const { HANABI_PROFILES } = await import('data:text/javascript;base64,' + Buffer.from(readTypeScript('hanabi/catalog.ts')).toString('base64'));
if (HANABI_PROFILES.length !== 50 || new Set(HANABI_PROFILES.map(profile => profile.family)).size !== 10)
    throw new Error('Unexpected Hanabi catalog size.');
const burst = value => value ? 'new(' + [
    str(value.kind), value.count, f(value.radius), f(value.duration), f(value.trail), f(value.twinkle)
].join(', ') + ')' : 'default';
const profiles = HANABI_PROFILES.map(p => {
    const t = p.text, r = p.region, c = p.camera;
    return '        new(' + [p.kind, p.family, p.mood, p.palette, p.burstAt].map(str).join(', ') + ',\n' +
        '            new(' + [str(t.layout), str(t.block), str(t.enter), str(t.sing), str(t.exit), f(t.heroSize),
            f(t.emphasis), f(t.tilt), f(t.stagger), t.outline, t.hardShadow].join(', ') + '),\n' +
        '            new(' + [r.cx, r.cy, r.w, r.h].map(f).join(', ') + '), new(' +
        [c.rise, c.push, c.roll, c.punch].map(f).join(', ') + '), ' + [p.launch, burst(p.burst), burst(p.sungBurst)].join(', ') + '),';
});
fs.writeFileSync(path.join(output, 'FoliaHanabi.Catalog.cs'), header +
    '\ninternal sealed partial class FoliaHanabi\n{\n    private static readonly Profile[] Profiles =\n    [\n' + profiles.join('\n') + '\n    ];\n}\n');

// Zero-browser module graph for the cold song planners. Segmentation comes from
// the same prepared Spectrum lyric input used by the other embedded planners.
const modules = new Map();
function add(id) {
    if (modules.has(id)) return;
    modules.set(id, '');
    let code;
    if (id.endsWith('utils/lyrics/wordSegmentation')) {
        code = 'export const segmentLyricWords = line => (line._segments ?? []).map(s => ({ ...s, segment: s.text, index: s.startOffset })); export const segmentTextWords = text => [{ segment: text, isWordLike: true }];';
    } else if (id === 'hanabi/text/blockLayout') {
        const source = fs.readFileSync(path.join(root, 'hanabi/text/blocks.ts'), 'utf8');
        const first = source.indexOf('export const blockLayoutParams');
        const last = source.indexOf('\n};', first);
        code = stripTypeScriptTypes(source.slice(first, last + 3));
    } else if (id === 'nebbia/nebbiaStrokes') {
        code = 'export const getNebbiaStrokeMedians = char => ({ length: activeStrokes?.[char] ?? 0 });';
    } else {
        code = readTypeScript(id + '.ts');
        if (id === 'nebbia/nebbiaBlocks') {
            const wideAdvance = 'if (isWideChar(ch)) return 1;';
            if (!code.includes(wideAdvance)) throw new Error('Missing Nebbia advance hook.');
            code = code.replace(wideAdvance, wideAdvance + `
    // Font skeletons use a .78 em font and the planner enlarges narrow glyphs by 1.15.
    // Budget extra room for the pen width and the handwriting warp.
    const advance = activeNebbiaWidths?.[ch];
    if (!CJK.test(ch) && Number.isFinite(advance) && advance > 0) return Math.max(.3, .9 * advance + .075);`);
        }
    }
    const exports = [];
    code = code.replace(/import\s*\{([^}]+)\}\s*from\s*['"]([^'"]+)['"];?/g, (_, names, specifier) => {
        const dependency = path.posix.normalize(path.posix.join(path.posix.dirname(id), specifier));
        add(dependency);
        return 'const { ' + names.split(',').map(s => s.trim().replace(/\s+as\s+/, ': ')).filter(Boolean).join(', ') +
            ' } = require(' + JSON.stringify(dependency) + ');';
    });
    code = code.replace(/export\s+(const|function|class)\s+(\w+)/g, (_, kind, name) => {
        exports.push(name);
        return kind + ' ' + name;
    });
    if (/^\s*(?:import|export)\s/m.test(code)) throw new Error('Unsupported module syntax in ' + id);
    modules.set(id, code.replace(/[ \t]+$/gm, '') + '\n' + exports.map(name => 'exports.' + name + ' = ' + name + ';').join('\n'));
}
for (const id of ['hanabi/hanabiProgram', 'hanabi/hanabiSceneFrames', 'hanabi/collage/collagePlan', 'hanabi/color', 'hanabi/mg/burstPlan', 'hanabi/text/layout', 'hanabi/text/animations', 'hanabi/text/blockLayout', 'metaphor/metaphorProgram', 'metaphor/metaphorLayout', 'metaphor/metaphorCamera', 'metaphor/metaphorFigures', 'metaphor/metaphorPalette', 'nebbia/nebbiaLayout', 'nebbia/nebbiaChars']) add(id);
const adapter = fs.readFileSync(new URL('./adapter.js', import.meta.url), 'utf8');
const table = [...modules].map(([id, code]) => JSON.stringify(id) + ': function (exports, require) {\n' + code + '\n}').join(',\n');
fs.writeFileSync(path.join(output, '../../External/Folia/native-stages.js'),
    '// Generated by Build/FoliaNative/sync.mjs from folia-major 6ee9404f (AGPL-3.0).\n' +
    'var FoliaNativeStages = (() => {\nconst modules = {\n' + table + '\n};\n' + adapter + '\n})();\n');
