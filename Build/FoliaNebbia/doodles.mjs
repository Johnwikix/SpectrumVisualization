import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import { readFile, writeFile } from 'node:fs/promises';

if (!process.argv[2]) throw new Error('Pass the folia-major checkout and optionally a Chromium executable.');
const upstream = resolve(process.argv[2]);
const packageRequire = createRequire(resolve(upstream, 'package.json'));
const lucide = resolve(upstream, 'node_modules/lucide-react');
const packageInfo = JSON.parse(await readFile(resolve(lucide, 'package.json'), 'utf8'));
if (packageInfo.version !== '1.48.0') throw new Error('Expected Lucide 1.48.0 from the pinned Folia checkout.');
const names = ['Heart', 'Star', 'Moon', 'Music', 'Flower', 'Sparkles', 'CloudRain', 'Umbrella', 'Smile', 'Leaf'];
const nodeEntries = {};
for (const name of names) {
    const key = name.replace(/[A-Z]/g, (value, index) => (index ? '-' : '') + value.toLowerCase());
    let source = pathToFileURL(resolve(lucide, 'dist/esm/icons', key + '.mjs'));
    let entry = await import(source);
    while (!entry.__iconData) {
        const alias = (await readFile(source, 'utf8')).match(/export \{ default \} from ['"]([^'"]+)['"]/);
        if (!alias) throw new Error('Missing icon anatomy for ' + name);
        source = new URL(alias[1], source);
        entry = await import(source);
    }
    nodeEntries[name] = entry.__iconData.node;
}

const { chromium } = packageRequire('playwright');
const browser = await chromium.launch({ executablePath: process.argv[3] });
let sampled;
try {
    const page = await browser.newPage({ offline: true });
    sampled = await page.evaluate(icons => {
        const ns = 'http://www.w3.org/2000/svg';
        const svg = document.createElementNS(ns, 'svg');
        svg.setAttribute('viewBox', '0 0 24 24');
        document.body.appendChild(svg);
        return Object.fromEntries(Object.entries(icons).map(([name, nodes]) => {
            const segments = [];
            for (const [tag, attrs] of nodes) {
                const element = document.createElementNS(ns, tag);
                for (const [key, value] of Object.entries(attrs)) if (key !== 'key') element.setAttribute(key, value);
                svg.appendChild(element);
                const length = element.getTotalLength();
                let previous = null;
                let first = true;
                for (let s = 0; s <= length; s += .7) {
                    const p = element.getPointAtLength(s);
                    if (previous && Math.hypot(p.x - previous.x, p.y - previous.y) <= 2.1) {
                        segments.push([previous.x / 24, previous.y / 24, p.x / 24, p.y / 24, first]);
                        first = false;
                    } else first = true;
                    previous = p;
                }
                svg.removeChild(element);
            }
            return [name, segments];
        }));
    }, nodeEntries);
} finally {
    await browser.close();
}
const target = new URL('../../Effects/Folia/FoliaNebbia.Doodles.cs', import.meta.url);
const value = number => `${Number(number.toFixed(6))}f`;
const arms = names.map(name => `        "${name}" =>\n        [\n${sampled[name].map(([x0,y0,x1,y1,first]) =>
    `            new(new(${value(x0)},${value(y0)}),new(${value(x1)},${value(y1)})${first ? ',true' : ''}),`).join('\n')}\n        ],`);
await writeFile(target, `// Generated by Build/FoliaNebbia/doodles.mjs from Lucide 1.48.0.\n// See External/Folia/Nebbia/LUCIDE-LICENSE.txt.\n\nnamespace WinExSpectrumTest.Effects.Folia;\n\ninternal sealed partial class FoliaNebbia\n{\n    private static FoliaNebbiaStrokes.Segment[] DoodleSegments(string icon) => icon switch\n    {\n${arms.join('\n')}\n        _ => []\n    };\n}\n`);
await writeFile(new URL('../../External/Folia/Nebbia/LUCIDE-LICENSE.txt', import.meta.url),
    await readFile(resolve(lucide, 'LICENSE')));
